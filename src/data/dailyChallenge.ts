/**
 * Returns today's challenge info and questions based on local UTC date string.
 * All players on the same calendar day receive the EXACT same fixed set of questions.
 */
export function getTodaysChallenge(date: Date = new Date()): {
  info: DailyChallengeInfo;
  questions: TriviaQuestion[];
} {
  const dayOfWeek = date.getDay(); // 0 to 6
  const dateKey = date.toISOString().split('T')[0]; // "2026-09-27"
  const scheduleItem = DAILY_CHALLENGE_SCHEDULE.find((s) => s.dayOfWeek === dayOfWeek) || DAILY_CHALLENGE_SCHEDULE[0];

  const info: DailyChallengeInfo = {
    dateKey,
    dayName: scheduleItem.dayName,
    category: scheduleItem.category,
    categoryName: scheduleItem.categoryName,
    categoryIcon: scheduleItem.categoryIcon,
    themeTitle: scheduleItem.themeTitle,
    description: scheduleItem.description,
    featuredHostId: scheduleItem.featuredHostId,
    difficulty: scheduleItem.difficulty,
    questionCount: scheduleItem.questionCount,
  };

  return {
    info,
    questions: scheduleItem.fixedQuestions,
  };
}
